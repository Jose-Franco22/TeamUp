// Regenerates dashboard-paste.ts: index.ts with prompt.js inlined, for anyone
// deploying through the Supabase Dashboard editor, which takes a single file.
//
// Run after changing index.ts or prompt.js:
//   node supabase/functions/fit-review/make-dashboard-paste.mjs
//
// The two-file version is the real one — it is what `supabase functions
// deploy` ships and what CI tests. dashboard-paste.ts exists so somebody
// without the CLI, or without push access to the Supabase project, can still
// get the function deployed from a browser.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const dir = dirname(fileURLToPath(import.meta.url));
const CR = String.fromCharCode(13);
const read = (name) => readFileSync(join(dir, name), 'utf8').split(CR).join('');

// Drop prompt.js's own header — it explains why the file is separate, which
// makes no sense once it isn't. Cut at the first declaration rather than at a
// marker string: a marker that stops matching returns -1, and slicing by that
// silently cuts the file mid-word instead of failing.
const promptSource = read('prompt.js');
const lines = promptSource.split('\n');
const firstDeclaration = lines.findIndex((line) => /^(export )?(const|function) /.test(line));
if (firstDeclaration === -1) {
  throw new Error('no declaration found in prompt.js — has it been restructured?');
}
const body = lines.slice(firstDeclaration).join('\n');

// Nothing is imported from this file once it is inlined, so the exports go
// too — Deno would accept them, but they would be misleading.
const inlined = body.replace(/^export /gm, '').trim();

const NOTE = [
  '// ---------------------------------------------------------------------',
  '// GENERATED — do not edit this file.',
  '//',
  '// This is index.ts with prompt.js inlined, for pasting into the Supabase',
  '// Dashboard editor (Edge Functions -> Deploy a new function -> Via Editor),',
  '// which takes one file. Name the function exactly `fit-review`.',
  '//',
  '// Edit index.ts or prompt.js instead, then run:',
  '//   node supabase/functions/fit-review/make-dashboard-paste.mjs',
  '//',
  '// `supabase functions deploy fit-review` ships the two-file version and is',
  '// the one that cannot drift. Use this only when the CLI is not an option.',
  '// ---------------------------------------------------------------------',
  '',
  inlined,
  '',
  '// --- the function itself ---------------------------------------------',
].join('\n');

const index = read('index.ts').replace(
  "import { buildPrompt, parseVerdict, RESPONSE_SCHEMA } from './prompt.js';",
  NOTE,
);

if (index.includes("from './prompt.js'")) {
  throw new Error('the import was not replaced — check index.ts');
}
for (const symbol of ['BANDS', 'RESPONSE_SCHEMA', 'buildPrompt', 'parseVerdict']) {
  if (!new RegExp(`^(function|const) ${symbol}\\b`, 'm').test(index)) {
    throw new Error(`${symbol} is missing from the generated file`);
  }
}

// Every line must be a comment, a blank, or part of something — a fragment
// left by a bad cut reads as a bare word at the start of a line, which is
// what shipped the first time this ran.
for (const [i, line] of index.split('\n').entries()) {
  if (/^[a-z]+\s+[a-z]/.test(line) && !/^(const|let|var|function|return|export|import|async|await|new|type|interface|if|for|while|else|try|catch|finally|throw|class|case|default|break|continue|do|switch|typeof|instanceof|delete|void|yield)\b/.test(line)) {
    throw new Error(`line ${i + 1} looks like a fragment, not code: ${line.slice(0, 60)}`);
  }
}

writeFileSync(join(dir, 'dashboard-paste.ts'), index, 'utf8');
console.log(`dashboard-paste.ts regenerated, ${index.split('\n').length} lines`);
