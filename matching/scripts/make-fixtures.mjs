// Generates the two TEMPORARY fixtures this prototype needs, which the live
// schema has nowhere to store yet. Seeded, so re-running produces identical
// files and tests stay reproducible.
//
//   node scripts/make-fixtures.mjs
//
//   fixtures/test-evidence.json  resume evidence for the students in mockData
//   fixtures/test-cohort.json    24 synthetic unteamed students to search over
//
// Replace both with real data once a profile_evidence table exists and real
// students have signed up.

import { writeFileSync } from 'node:fs';
import { skills, userSkills } from '../../frontend/src/api/mockData.js';

// mulberry32, a tiny seeded generator so fixtures never drift between runs.
function seeded(seed) {
  return function next() {
    seed = (seed + 0x6d2b79f5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const rand = seeded(20260916);
const between = (lo, hi) => lo + Math.floor(rand() * (hi - lo + 1));
const pick = (list) => list[Math.floor(rand() * list.length)];

const NOTE = 'TEMPORARY TEST DATA, not real students. Generated by scripts/make-fixtures.mjs.';

// --- Evidence for the students already in mockData ---------------------------
const evidence = {};
for (const row of userSkills) {
  (evidence[row.user_id] ??= {})[row.skill_id] = { months: between(2, 30), projects: between(0, 4) };
}
writeFileSync(
  new URL('../fixtures/test-evidence.json', import.meta.url),
  JSON.stringify({ _comment: NOTE, evidence }, null, 2) + '\n',
);

// --- A cohort big enough to search over --------------------------------------
const COUNT = 24;
const cohortUsers = [];
const cohortSkills = [];
const cohortEvidence = {};

for (let i = 1; i <= COUNT; i++) {
  const id = `syn-${String(i).padStart(2, '0')}`;
  cohortUsers.push({ id, name: `Test Student ${i}`, availability_hours: between(4, 20) });

  const chosen = new Set();
  const howMany = between(2, 5);
  while (chosen.size < howMany) chosen.add(pick(skills).id);

  for (const skillId of chosen) {
    cohortSkills.push({ user_id: id, skill_id: skillId, source: rand() < 0.6 ? 'resume' : 'manual' });
    (cohortEvidence[id] ??= {})[skillId] = { months: between(1, 28), projects: between(0, 3) };
  }
}

writeFileSync(
  new URL('../fixtures/test-cohort.json', import.meta.url),
  JSON.stringify(
    { _comment: NOTE, users: cohortUsers, user_skills: cohortSkills, evidence: cohortEvidence },
    null,
    2,
  ) + '\n',
);

console.log(`Wrote evidence for ${Object.keys(evidence).length} mock students and a cohort of ${COUNT} synthetic students.`);
